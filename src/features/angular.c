int vm_angular_count(const int n)
{
    switch (n) {
    case 2: return 8;
    case 4: return 24;
    case 6: return 48;
    case 8: return 80;
    default: return 0;
    }
}

int vm_angular_sn(const int n, vm_float_t *mu, vm_float_t *eta,
                  vm_float_t *xi, vm_float_t *w)
{
    const int count = vm_angular_count(n);
    if (count == 0 || !mu || !eta || !xi || !w) {
        return 0;
    }

    const vm_float_t *sm = NULL;
    const vm_float_t *se = NULL;
    const vm_float_t *sx = NULL;
    const vm_float_t *sw = NULL;

    switch (n) {
    case 2: sm = sn2_mu; se = sn2_eta; sx = sn2_xi; sw = sn2_w; break;
    case 4: sm = sn4_mu; se = sn4_eta; sx = sn4_xi; sw = sn4_w; break;
    case 6: sm = sn6_mu; se = sn6_eta; sx = sn6_xi; sw = sn6_w; break;
    case 8: sm = sn8_mu; se = sn8_eta; sx = sn8_xi; sw = sn8_w; break;
    default: return 0;
    }

    for (int i = 0; i < count; ++i) {
        mu[i] = sm[i];
        eta[i] = se[i];
        xi[i] = sx[i];
        w[i] = sw[i];
    }

    return count;
}

vm_float_t vm_angular_isotropic(void)
{
    return VM_F(1.0) / (VM_F(4.0) * M_PI);
}

vm_float_t vm_angular_hg(const vm_float_t mu, const vm_float_t g)
{
    const vm_float_t g2 = g * g;
    const vm_float_t denom = VM_F(1.0) + g2 - VM_F(2.0) * g * mu;
    const vm_float_t root = VECMAT_SQRT(denom);

    return (VM_F(1.0) - g2) / (VM_F(4.0) * M_PI * root * root * root);
}

vm_float_t vm_angular_scatter(const vm_float_t *mu,
                              const vm_float_t *eta,
                              const vm_float_t *xi,
                              const vm_float_t *w,
                              const vm_float_t *I,
                              const int n,
                              const vm_float_t ox, const vm_float_t oy, const vm_float_t oz,
                              const vm_float_t g)
{
    if (!mu || !eta || !xi || !w || !I || n <= 0) {
        return VM_F(0.0);
    }

    vm_float_t acc = VM_F(0.0);
    for (int m = 0; m < n; ++m) {
        const vm_float_t cos_ang = mu[m] * ox + eta[m] * oy + xi[m] * oz;
        const vm_float_t phase = (g == VM_F(0.0))
            ? vm_angular_isotropic()
            : vm_angular_hg(cos_ang, g);
        acc += w[m] * phase * I[m];
    }

    return acc;
}
